import { betterAuth } from "better-auth";
import { drizzleAdapter } from "better-auth/adapters/drizzle";
import { nextCookies } from "better-auth/next-js";
import { db } from "@/db";
import * as authSchema from "@/db/auth-schema"; // generated by `npx auth@latest generate`

// The auth "engine": runs on the server only (it uses the database and BETTER_AUTH_SECRET).
// It reads BETTER_AUTH_SECRET and BETTER_AUTH_URL from the environment by itself.
export const auth = betterAuth({
  // Where users and sessions are stored: your Neon database, through Drizzle.
  database: drizzleAdapter(db, {
    provider: "pg", // Postgres
    schema: authSchema, // the exact user/session/account/verification tables
  }),

  // Log in with email + password. Better Auth hashes passwords; we never see them.
  emailAndPassword: {
    enabled: true,
  },

  // Lets Server Actions set the login cookie. Must stay the LAST plugin.
  plugins: [nextCookies()],
});
